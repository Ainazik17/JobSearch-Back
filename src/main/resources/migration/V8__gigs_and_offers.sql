-- Подработка (DESIGN_SPEC 6.4 / 6.4b): разовые задания и услуги исполнителей

-- Разовое задание: «нужен человек на пару часов»
create table if not exists gigs
(
    id           bigint generated by default as identity primary key,
    user_id      bigint       not null references users (id) on delete cascade,
    city_id      integer      not null references cities (id),
    title        varchar(255) not null,          -- «Что нужно сделать»
    work_date    date         not null,          -- «Когда» (сегодня / завтра / выбранная дата)
    time_text    varchar(120),                   -- «15:00, примерно 3 часа»
    pay          integer      not null,          -- «Оплата, сом»
    pay_unit     varchar(20)  not null default 'TOTAL'
        constraint gigs_pay_unit_check check (pay_unit in ('TOTAL', 'HOUR', 'SHIFT')),
    people_count varchar(5)   not null default '1', -- «1».. «5+»
    address      varchar(255) not null,
    latitude     double precision,
    longitude    double precision,
    urgent       boolean      not null default false,
    phone        varchar(20),
    is_active    boolean      not null default true,
    created_at   timestamp(6) not null default now(),
    updated_at   timestamp(6)
);

create index if not exists idx_gigs_active_date on gigs (is_active, work_date);
create index if not exists idx_gigs_user on gigs (user_id);

-- Мои услуги: исполнитель готов к подработке (одна карточка на пользователя)
create table if not exists worker_offers
(
    id         bigint generated by default as identity primary key,
    user_id    bigint       not null unique references users (id) on delete cascade,
    city_id    integer      not null references cities (id),
    skills     varchar(1000) not null,          -- профессии через «|»: «Няня|Репетитор»
    price      integer      not null,           -- «Цена, сом»
    price_unit varchar(20)  not null default 'HOUR'
        constraint worker_offers_price_unit_check check (price_unit in ('HOUR', 'VISIT', 'SHIFT')),
    days       varchar(40)  not null,           -- «Пн,Вт,Сб»
    district   varchar(255),                    -- «Район работы»
    about      text,                            -- «Коротко о себе»
    phone      varchar(20),
    is_active  boolean      not null default true,
    created_at timestamp(6) not null default now(),
    updated_at timestamp(6)
);

create index if not exists idx_worker_offers_active_city on worker_offers (is_active, city_id);
