-- Сериал Work KG в Mini App: 1-я серия бесплатно, остальные — при любом активном тарифе (PRO)

create table if not exists series
(
    id          bigint generated by default as identity primary key,
    title       varchar(255) not null,
    description text,
    cover_url   varchar(500),
    sort_order  integer      not null default 0,
    is_active   boolean      not null default true,
    created_at  timestamp(6) not null default now(),
    updated_at  timestamp(6)
);

create table if not exists series_episodes
(
    id            bigint generated by default as identity primary key,
    series_id     bigint       not null references series (id) on delete cascade,
    number        integer      not null,
    title         varchar(255) not null,
    description   text,
    video_url     varchar(500),          -- ссылка на YouTube («Доступ по ссылке»)
    thumbnail_url varchar(500),
    duration_sec  integer,
    is_free       boolean      not null default false, -- серия 1 бесплатна всегда, флаг — для дополнительных
    is_published  boolean      not null default true,
    created_at    timestamp(6) not null default now(),
    updated_at    timestamp(6),
    constraint uk_series_episode_number unique (series_id, number)
);

create index if not exists idx_series_episodes_series on series_episodes (series_id, number);
