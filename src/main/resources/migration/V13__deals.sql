-- Сделки (DESIGN_SPEC 7): «Работали вместе?» одним касанием, отзывы только по сделке

create table if not exists deals
(
    id                    bigint generated by default as identity primary key,
    worker_id             bigint       not null references users (id) on delete cascade,
    employer_id           bigint       not null references users (id) on delete cascade,
    vacancy_id            bigint references vacancies (id) on delete set null,
    gig_id                bigint references gigs (id) on delete set null,
    title                 varchar(255) not null,      -- «Официант на банкет»
    source                varchar(20)  not null
        constraint deals_source_check check (source in ('INVITE', 'HIRE', 'FOUND')),
    status                varchar(20)  not null
        constraint deals_status_check check (status in
            ('ASK_WORKER', 'AWAIT_WORKER', 'AWAIT_EMPLOYER', 'CONFIRMED', 'DISPUTED', 'PROOF_REVIEW', 'DECLINED')),
    ask_after             timestamp(6),               -- вопрос исполнителю появляется не раньше
    due_at                timestamp(6),               -- автоподтверждение, если вторая сторона молчит
    notified_at           timestamp(6),               -- когда отправили вопрос в бот
    confirmed_at          timestamp(6),
    points_awarded        boolean      not null default false,
    -- исполнитель оценивает работодателя
    worker_stars          smallint check (worker_stars between 1 and 5),
    worker_paid           smallint check (worker_paid between 1 and 5),
    worker_conditions     smallint check (worker_conditions between 1 and 5),
    worker_attitude       smallint check (worker_attitude between 1 and 5),
    worker_text           text,
    -- работодатель оценивает исполнителя
    employer_stars        smallint check (employer_stars between 1 and 5),
    employer_punctual     smallint check (employer_punctual between 1 and 5),
    employer_quality      smallint check (employer_quality between 1 and 5),
    employer_communication smallint check (employer_communication between 1 and 5),
    employer_text         text,
    created_at            timestamp(6) not null default now(),
    updated_at            timestamp(6)
);
create unique index if not exists uq_deals_worker_vacancy on deals (worker_id, vacancy_id) where vacancy_id is not null;
create index if not exists idx_deals_worker on deals (worker_id, status);
create index if not exists idx_deals_employer on deals (employer_id, status);
create index if not exists idx_deals_due on deals (status, due_at);

-- «Докажите, что работали» [24]
create table if not exists deal_proofs
(
    id         bigint generated by default as identity primary key,
    deal_id    bigint       not null references deals (id) on delete cascade,
    kind       varchar(20)  not null
        constraint deal_proofs_kind_check check (kind in ('CHAT', 'PHOTO', 'PAYMENT', 'CONTRACT')),
    file_url   varchar(500) not null,
    created_at timestamp(6) not null default now()
);

-- Отзыв на профиле компании ↔ сделка (один отзыв на сделку)
alter table company_reviews add column if not exists deal_id bigint references deals (id) on delete cascade;
create unique index if not exists uq_company_reviews_deal on company_reviews (deal_id) where deal_id is not null;

