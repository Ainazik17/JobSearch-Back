-- Компании (DESIGN_SPEC 4, 5): профиль работодателя, фото, подписки, отзывы сотрудников

-- Одна компания на пользователя-работодателя; её вакансии — активные вакансии владельца
create table if not exists companies
(
    id           bigint generated by default as identity primary key,
    user_id      bigint       not null unique references users (id) on delete cascade,
    city_id      integer references cities (id),
    name         varchar(120) not null,
    type         varchar(120),                  -- «Ресторан турецкой кухни»
    sphere       varchar(60),                   -- одна из 24 сфер Главной
    tagline      varchar(140),                  -- цитата на обложке
    about        text,
    perks        varchar(600),                  -- через «|»: «🍽 Питание|👔 Форма»
    staff        varchar(20),                   -- «120+»
    cover_url    varchar(500),
    verified     boolean      not null default false, -- ставит админ
    hired_count  integer      not null default 0,     -- «наняли здесь», растёт со Сделками
    created_at   timestamp(6) not null default now(),
    updated_at   timestamp(6)
);
create index if not exists idx_companies_sphere on companies (sphere);

create table if not exists company_photos
(
    id            bigint generated by default as identity primary key,
    company_id    bigint       not null references companies (id) on delete cascade,
    file_url      varchar(500) not null,
    caption       varchar(60),
    display_order integer      not null default 0,
    uploaded_at   timestamp(6) not null default now()
);
create index if not exists idx_company_photos_company on company_photos (company_id);

-- «Подписаться на вакансии»
create table if not exists company_followers
(
    id         bigint generated by default as identity primary key,
    company_id bigint       not null references companies (id) on delete cascade,
    user_id    bigint       not null references users (id) on delete cascade,
    created_at timestamp(6) not null default now(),
    constraint uq_company_follower unique (company_id, user_id)
);
create index if not exists idx_company_followers_user on company_followers (user_id);

-- Отзывы сотрудников (появляются из Сделок: «Работали вместе?» → оценка)
create table if not exists company_reviews
(
    id             bigint generated by default as identity primary key,
    company_id     bigint       not null references companies (id) on delete cascade,
    author_user_id bigint references users (id) on delete set null,
    author_role    varchar(80)  not null,       -- «Официант»
    tenure_text    varchar(40),                 -- «работал 8 мес.»
    stars          smallint     not null check (stars between 1 and 5),
    paid_on_time   smallint check (paid_on_time between 1 and 5),
    conditions     smallint check (conditions between 1 and 5),
    attitude       smallint check (attitude between 1 and 5),
    text           text,
    disputed       boolean      not null default false,
    created_at     timestamp(6) not null default now()
);
create index if not exists idx_company_reviews_company on company_reviews (company_id);
