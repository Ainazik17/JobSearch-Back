-- Отклики резюме глазами работодателя: история работы в резюме

-- «Где работали»: место, должность, срок (необязательно, до 5 записей на резюме)
create table if not exists resume_work_places
(
    id            bigint generated by default as identity primary key,
    resume_id     bigint       not null references resumes (id) on delete cascade,
    place         varchar(120) not null,   -- «Tash Kitchen»
    role          varchar(120),            -- «Официант»
    period_text   varchar(60),             -- «2 года», «2022–2024»
    display_order integer      not null default 0
);
create index if not exists idx_resume_work_places_resume on resume_work_places (resume_id);

