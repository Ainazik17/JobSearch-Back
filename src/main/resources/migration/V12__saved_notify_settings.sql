-- Сохранённые вакансии (сердечко) и настройки уведомлений

create table if not exists saved_vacancies
(
    id         bigint generated by default as identity primary key,
    user_id    bigint       not null references users (id) on delete cascade,
    vacancy_id bigint       not null references vacancies (id) on delete cascade,
    created_at timestamp(6) not null default now(),
    constraint uq_saved_vacancy unique (user_id, vacancy_id)
);
create index if not exists idx_saved_vacancies_user on saved_vacancies (user_id);

-- Какие рассылки присылать (по умолчанию все)
alter table users add column if not exists notify_vacancies boolean not null default true; -- новые вакансии под моё резюме
alter table users add column if not exists notify_resumes   boolean not null default true; -- новые резюме под мою вакансию
alter table users add column if not exists notify_gigs      boolean not null default true; -- подработка под «Мои услуги»
alter table users add column if not exists notify_companies boolean not null default true; -- вакансии компаний, на которые подписан
